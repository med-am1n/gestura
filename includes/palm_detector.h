    std::vector<PalmDetection> detect(const cv::Mat& frame) {
        if (frame.empty()) return {};

        cv::Point2i padBias;
        std::vector<float> input = preprocess(frame, padBias);

        const std::vector<int64_t> shape = {1, 192, 192, 3};

        auto memoryInfo = Ort::MemoryInfo::CreateCpu(OrtAllocatorType::OrtArenaAllocator, OrtMemTypeDefault);

        auto tensor = Ort::Value::CreateTensor<float>(memoryInfo, input.data(), input.size(), shape.data(), shape.size());
        
        // Ort::AllocatorWithDefaultOptions allocator;
        //
        // size_t input_modes_size = session_.GetInputCount();
        // for(size_t i=0; i< input_modes_size; i++){
        //   Ort::AllocatedStringPtr input_name = session_.GetInputNameAllocated(i, allocator);
        //   std::cout << "Input Name "<<i << ": "<<input_name.get()<<std::endl;
        // }
        //
        // size_t output_modes_size = session_.GetOutputCount();
        // for(size_t i=0; i< output_modes_size; i++){
        //   Ort::AllocatedStringPtr output_name = session_.GetOutputNameAllocated(i, allocator);
        //   std::cout << "Output Name "<<i << ": "<<output_name.get()<<std::endl;
        // }
        
        const char* inputNames[] = {"input_1"};
        const char* outputNames[] = {"Identity", "Identity_1"};

        auto outputs = session_.Run(Ort::RunOptions{nullptr}, inputNames, &tensor, 1, outputNames, 2);

        const float* regressions = outputs[0].GetTensorData<float>();

        const float* scores = outputs[1].GetTensorData<float>();

        return postprocess(regressions, scores, frame.size(), padBias);
    }

    static void draw(cv::Mat& frame, const std::vector<PalmDetection>& detections) {
        
      for (const auto& detection : detections) {

            cv::rectangle(frame, detection.box, cv::Scalar(0, 255, 0), 2);
            cv::putText(frame, cv::format("%.2f", detection.score),
            cv::Point(static_cast<int>(detection.box.x), std::max(15, static_cast<int>(detection.box.y))), cv::FONT_HERSHEY_SIMPLEX, 0.5, cv::Scalar(0, 255, 0), 1);

            for (const auto& point : detection.landmarks) {
                cv::circle(frame, point, 3, cv::Scalar(0, 0, 255), -1);
            }
        }
    }

private:
    Ort::Env env_;
    Ort::Session session_;
    std::vector<cv::Point2f> anchors_;

    std::vector<float> preprocess(const cv::Mat& frame, cv::Point2i& padBias) {
        
        const float ratio = std::min(192.0f / frame.cols, 192.0f / frame.rows);

        const int resizedWidth = static_cast<int>(frame.cols * ratio);

        const int resizedHeight = static_cast<int>(frame.rows * ratio);

        cv::Mat resized;
        cv::resize(frame, resized, cv::Size(resizedWidth, resizedHeight));

        const int padW = 192 - resizedWidth;
        const int padH = 192 - resizedHeight;

        const int left = padW / 2;
        const int top = padH / 2;

        cv::Mat padded;
        cv::copyMakeBorder(resized, padded, top, padH - top, left, padW - left, cv::BORDER_CONSTANT, cv::Scalar(0, 0, 0));

        cv::Mat rgb;
        cv::cvtColor(padded, rgb, cv::COLOR_BGR2RGB);

        cv::Mat floatImage;
        rgb.convertTo(floatImage, CV_32FC3, 1.0 / 255.0);

        // NHWC: [1, 192, 192, 3]
        std::vector<float> input(192 * 192 * 3);

        for (int y = 0; y < 192; ++y) {
            const cv::Vec3f* row =
                floatImage.ptr<cv::Vec3f>(y);

            for (int x = 0; x < 192; ++x) {
                const int i = (y * 192 + x) * 3;

                input[i]     = row[x][0]; // R
                input[i + 1] = row[x][1]; // G
                input[i + 2] = row[x][2]; // B
            }
        }

        // Convert padding offsets back to original-image coordinates.
        padBias.x = static_cast<int>(left / ratio);
        padBias.y = static_cast<int>(top / ratio);

        return input;
    }

    std::vector<PalmDetection> postprocess(const float* regressions, const float* scores, const cv::Size& originalSize, const cv::Point2i& padBias) {

        constexpr float scoreThreshold = 0.5f;
        constexpr float nmsThreshold = 0.3f;

        const float scale = static_cast<float>(std::max(originalSize.width, originalSize.height));

        std::vector<PalmDetection> candidates;
        std::vector<cv::Rect> boxes;
        std::vector<float> confidence;

        for (int i = 0; i < NUM_ANCHORS; ++i) {
            const float logit = scores[i];
            const float score =1.0f / (1.0f + std::exp(-logit));

            if (score < scoreThreshold) continue;

            const float* r = regressions + i * 18;
            const cv::Point2f anchor = anchors_[i];

            const float cx = (r[0] / 192.0f + anchor.x) * scale - padBias.x;

            const float cy = (r[1] / 192.0f + anchor.y) * scale - padBias.y;

            const float w = r[2] / 192.0f * scale;
            const float h = r[3] / 192.0f * scale;

            PalmDetection detection;

            detection.box = cv::Rect2f(cx - w / 2, cy - h / 2, w, h);

            detection.score = score;

            for (int j = 0; j < 7; ++j) {

                float x = (r[4 + j * 2] / 192.0f + anchor.x)* scale - padBias.x;
                float y = (r[5 + j * 2] / 192.0f + anchor.y) * scale - padBias.y;\

                detection.landmarks.emplace_back(x, y);
            }

            boxes.emplace_back(
                static_cast<int>(detection.box.x),
                static_cast<int>(detection.box.y),
                static_cast<int>(detection.box.width),
                static_cast<int>(detection.box.height)
            );

            confidence.push_back(score);
            candidates.push_back(std::move(detection));
        }

        std::vector<int> keep;
        cv::dnn::NMSBoxes(boxes, confidence, scoreThreshold, nmsThreshold, keep);

        std::vector<PalmDetection> result;
        result.reserve(keep.size());

        for (int index : keep) {
            result.push_back(candidates[index]);
        }

        return result;
    }

